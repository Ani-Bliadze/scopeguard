"""Static, server-owned configuration. Nothing here is settable by the model, the worker or the browser."""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass, field
from pathlib import Path

from dotenv import dotenv_values

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RUNTIME_DIR = PROJECT_ROOT / ".runtime"
CONFIG_DIR = PROJECT_ROOT / "config"
DB_PATH = RUNTIME_DIR / "scopeguard.sqlite"
AUDIT_DB_PATH = RUNTIME_DIR / "audit.sqlite"
BACKEND_ENV_PATH = RUNTIME_DIR / "backend.env"
FRONTEND_DIST = PROJECT_ROOT / "frontend" / "dist"
PYTHON = sys.executable

BIND_HOST = "127.0.0.1"
DEFAULT_PORT = 8000


def _env() -> dict[str, str]:
    values = {k: v for k, v in dotenv_values(PROJECT_ROOT / ".env").items() if v is not None}
    # Process environment wins so tests/CI can force modes without editing .env.
    for key in (
        "SCOPEGUARD_MODE",
        "OPENAI_API_KEY",
        "OPENAI_MODEL",
        "GEMINI_API_KEY",
        "GEMINI_MODEL",
        "SCOPEGUARD_ENABLE_APPROVALS",
        "SCOPEGUARD_ENABLE_INJECTION_DEMO",
    ):
        if key in os.environ:
            values[key] = os.environ[key]
    return values


@dataclass(frozen=True)
class Settings:
    mode: str = "deterministic"
    openai_api_key: str = field(default="", repr=False)
    openai_model: str = ""
    gemini_api_key: str = field(default="", repr=False)
    gemini_model: str = ""
    enable_approvals: bool = True
    port: int = DEFAULT_PORT
    upstream_timeout_s: float = 5.0
    planner_timeout_s: float = 15.0
    answer_timeout_s: float = 10.0
    task_timeout_s: float = 45.0
    # Test hook: replace an upstream server module with a fixture (never settable via API).
    upstream_overrides: tuple[tuple[str, str], ...] = ()
    upstream_extra_env: tuple[tuple[str, str], ...] = ()

    @property
    def live_provider(self) -> str | None:
        if self.mode != "live":
            return None
        if self.openai_api_key and self.openai_model:
            return "openai"
        if self.gemini_api_key and self.gemini_model:
            return "gemini"
        return None


def load_settings(**overrides) -> Settings:
    env = _env()
    base = Settings(
        mode=(env.get("SCOPEGUARD_MODE") or "deterministic").strip().lower(),
        openai_api_key=env.get("OPENAI_API_KEY", "").strip(),
        openai_model=env.get("OPENAI_MODEL", "").strip(),
        gemini_api_key=env.get("GEMINI_API_KEY", "").strip(),
        gemini_model=env.get("GEMINI_MODEL", "").strip(),
        enable_approvals=env.get("SCOPEGUARD_ENABLE_APPROVALS", "1").strip() == "1",
    )
    if overrides:
        from dataclasses import replace

        base = replace(base, **overrides)
    return base


def read_backend_credential() -> str | None:
    """Synthetic CRM credential generated by reset_demo. Only the upstream lifecycle owner calls this."""
    if not BACKEND_ENV_PATH.exists():
        return None
    return dotenv_values(BACKEND_ENV_PATH).get("SCOPEGUARD_CRM_CREDENTIAL")
